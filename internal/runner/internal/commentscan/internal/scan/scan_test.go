package scan_test

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/rabbytesoftware/agent-protection/internal/report"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/commentscan/internal/lexeme"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/commentscan/internal/scan"
)

const noteExtension = ".note"

func TestScanSnippet(
	t *testing.T,
) {
	root := t.TempDir()
	write(
		t,
		filepath.Join(
			root,
			"a.note",
		),
		"x\n",
	)
	findings, err := scan.Scan(
		root,
		nil,
		noteLanguages(),
	)
	want := []report.Finding{{Rule: "R07", Location: "a.note:1", Snippet: "comment: delete it and make the code say it through names and structure"}}
	isWrong := err != nil || !slices.Equal(
		findings,
		want,
	)
	if isWrong {
		t.Errorf(
			"Scan() = %v, %v, want %v",
			findings,
			err,
			want,
		)
	}
}

func TestScanGenerated(
	t *testing.T,
) {
	padding := strings.Repeat(
		"a",
		600,
	)
	cases := []struct {
		name string
		code string
		want []string
	}{
		{name: "generated header exempts the file", code: "Code generated by protoc. DO NOT EDIT.\n", want: nil},
		{name: "rust generated marker exempts the file", code: "@generated by build.rs\n", want: nil},
		{name: "generated marker past the header window does not exempt", code: padding + "\nCode generated\n", want: []string{"a.note:1"}},
	}
	for _, tc := range cases {
		assertScanned(
			t,
			tc.name,
			map[string]string{"a.note": tc.code},
			nil,
			tc.want,
		)
	}
}

func TestScanRejectsMissingRoot(
	t *testing.T,
) {
	_, err := scan.Scan(
		filepath.Join(
			t.TempDir(),
			"missing",
		),
		nil,
		noteLanguages(),
	)
	if err == nil {
		t.Error("Scan() error = nil, want one for a missing root")
	}
}

func TestScanRejectsUnreadableFile(
	t *testing.T,
) {
	root := t.TempDir()
	path := filepath.Join(
		root,
		"a.note",
	)
	write(
		t,
		path,
		"x\n",
	)
	err := os.Chmod(
		path,
		0o000,
	)
	if err != nil {
		t.Fatalf(
			"chmod %s: %v",
			path,
			err,
		)
	}

	_, err = scan.Scan(
		root,
		nil,
		noteLanguages(),
	)
	if err == nil {
		t.Error("Scan() error = nil, want one for an unreadable file")
	}
}

func noteLanguages() (languages []lexeme.Language) {
	return []lexeme.Language{{Matches: isNote, Spans: wholeText}}
}

func isNote(
	name string,
) (matched bool) {
	return filepath.Ext(name) == noteExtension
}

func wholeText(
	text []byte,
) (spans []lexeme.Span) {
	return []lexeme.Span{{Start: 0, End: len(text)}}
}

func noSpans(
	_ []byte,
) (spans []lexeme.Span) {
	return nil
}

func assertScanned(
	t *testing.T,
	name string,
	files map[string]string,
	excluded []string,
	want []string,
) {
	t.Helper()
	root := t.TempDir()
	for path, code := range files {
		write(
			t,
			filepath.Join(
				root,
				path,
			),
			code,
		)
	}

	findings, err := scan.Scan(
		root,
		excluded,
		noteLanguages(),
	)
	if err != nil {
		t.Fatalf(
			"%s: Scan() error = %v",
			name,
			err,
		)
	}

	assertLocations(
		t,
		name,
		findings,
		want,
	)
}

func assertLocations(
	t *testing.T,
	name string,
	findings []report.Finding,
	want []string,
) {
	t.Helper()
	got := []string{}
	for _, finding := range findings {
		got = append(
			got,
			finding.Location,
		)
	}

	isWrong := !slices.Equal(
		got,
		want,
	) && len(got)+len(want) > 0
	if isWrong {
		t.Errorf(
			"%s: locations = %v, want %v",
			name,
			got,
			want,
		)
	}
}

func write(
	t *testing.T,
	path string,
	content string,
) {
	t.Helper()
	err := os.MkdirAll(
		filepath.Dir(path),
		0o755,
	)
	if err != nil {
		t.Fatalf(
			"mkdir %s: %v",
			path,
			err,
		)
	}

	err = os.WriteFile(
		path,
		[]byte(content),
		0o600,
	)
	if err != nil {
		t.Fatalf(
			"write %s: %v",
			path,
			err,
		)
	}
}
