package comments_test

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/rabbytesoftware/agent-protection/internal/report"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/comments"
)

type sourceCase struct {
	name string
	path string
	code string
	want []string
}

func TestComments(
	t *testing.T,
) {
	padding := strings.Repeat(
		"a",
		600,
	)
	cases := []sourceCase{
		{name: "line comment in a ts file is reported", path: "a.ts", code: "const a = 1;\n// note\n", want: []string{"R07 a.ts:2"}},
		{name: "line comment in a rust file is reported", path: "src/a.rs", code: "fn a() {}\n// note\n", want: []string{"R07 src/a.rs:2"}},
		{name: "code without comments passes", path: "a.ts", code: "const a = 1;\n", want: nil},
		{name: "generated header exempts the file", path: "a.ts", code: "// Code generated by protoc. DO NOT EDIT.\n// more\n", want: nil},
		{name: "rust generated marker exempts the file", path: "a.rs", code: "// @generated by build.rs\nfn a() {}\n", want: nil},
		{name: "generated marker past the header window does not exempt", path: "a.ts", code: "// x\n" + padding + "\n// Code generated\n", want: []string{"R07 a.ts:1", "R07 a.ts:3"}},
		{name: "unlisted extension is not scanned", path: "a.py", code: "// not scanned\n", want: nil},
	}
	for _, tc := range cases {
		assertScanned(
			t,
			tc,
		)
	}
}

func TestCommentsSnippet(
	t *testing.T,
) {
	root := t.TempDir()
	write(
		t,
		filepath.Join(
			root,
			"a.ts",
		),
		"// note\n",
	)
	findings, err := comments.Comments(
		root,
		[]string{".ts"},
	)
	if err != nil {
		t.Fatalf(
			"Comments() error = %v",
			err,
		)
	}

	want := []report.Finding{{Rule: "R07", Location: "a.ts:1", Snippet: "comment: delete it and make the code say it through names and structure"}}
	if !slices.Equal(
		findings,
		want,
	) {
		t.Errorf(
			"Comments() = %v, want %v",
			findings,
			want,
		)
	}
}

func TestCommentsRejectsMissingRoot(
	t *testing.T,
) {
	_, err := comments.Comments(
		filepath.Join(
			t.TempDir(),
			"missing",
		),
		[]string{".ts"},
	)
	if err == nil {
		t.Error("Comments() error = nil, want one for a missing root")
	}
}

func TestCommentsRejectsUnreadableFile(
	t *testing.T,
) {
	root := t.TempDir()
	path := filepath.Join(
		root,
		"a.ts",
	)
	write(
		t,
		path,
		"// note\n",
	)
	err := os.Chmod(
		path,
		0o000,
	)
	if err != nil {
		t.Fatalf(
			"chmod %s: %v",
			path,
			err,
		)
	}

	_, err = comments.Comments(
		root,
		[]string{".ts"},
	)
	if err == nil {
		t.Error("Comments() error = nil, want one for an unreadable file")
	}
}

func assertScanned(
	t *testing.T,
	tc sourceCase,
) {
	t.Helper()
	root := t.TempDir()
	write(
		t,
		filepath.Join(
			root,
			tc.path,
		),
		tc.code,
	)
	findings, err := comments.Comments(
		root,
		[]string{".rs", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts"},
	)
	if err != nil {
		t.Fatalf(
			"%s: Comments() error = %v",
			tc.name,
			err,
		)
	}

	assertFindings(
		t,
		tc.name,
		findings,
		tc.want,
	)
}

func assertFindings(
	t *testing.T,
	name string,
	findings []report.Finding,
	want []string,
) {
	t.Helper()
	got := []string{}
	for _, finding := range findings {
		got = append(
			got,
			finding.Rule+" "+finding.Location,
		)
	}

	if !slices.Equal(
		got,
		want,
	) {
		t.Errorf(
			"%s: findings = %v, want %v",
			name,
			got,
			want,
		)
	}
}

func write(
	t *testing.T,
	path string,
	content string,
) {
	t.Helper()
	err := os.MkdirAll(
		filepath.Dir(path),
		0o755,
	)
	if err != nil {
		t.Fatalf(
			"mkdir %s: %v",
			path,
			err,
		)
	}

	err = os.WriteFile(
		path,
		[]byte(content),
		0o600,
	)
	if err != nil {
		t.Fatalf(
			"write %s: %v",
			path,
			err,
		)
	}
}
