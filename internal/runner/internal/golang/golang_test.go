func TestGolang(
	t *testing.T,
) {
	root := t.TempDir()
	writeFile(
		t,
		filepath.Join(
			root,
			"go.mod",
		),
		"module example.com/fixture\n\ngo 1.24\n",
	)
	writeFile(
		t,
		filepath.Join(
			root,
			"branch.go",
		),
		"package fixture\n\n// Branch picks a label.\nfunc Branch(x bool) (label string) {\n\tif x {\n\t\treturn \"yes\"\n\t} else {\n\t\treturn \"no\"\n\t}\n}\n",
	)
	findings, err := golang.Golang(root)
	if err != nil {
		t.Fatalf(
			"Golang() error = %v",
			err,
		)
	}

	got := ruleIDs(findings)
	for _, want := range []string{"R01", "R03", "R42"} {
		assertContains(
			t,
			got,
			want,
		)
	}
}

func TestGolangErrors(
	t *testing.T,
) {
	missing := filepath.Join(
		t.TempDir(),
		"missing",
	)
	withoutLinter := t.TempDir()
	writeFile(
		t,
		filepath.Join(
			withoutLinter,
			"go.mod",
		),
		"module example.com/fixture\n\ngo 1.24\n",
	)
	cases := []struct {
		root string
		path string
	}{
		{root: missing, path: os.Getenv("PATH")},
		{root: withoutLinter, path: t.TempDir()},
	}
	for _, tc := range cases {
		assertGolangError(
			t,
			tc.root,
			tc.path,
		)
	}
}

func TestFix(
	t *testing.T,
) {
	root := fixModule(t)
	original := readFile(
		t,
		filepath.Join(
			root,
			"join.go",
		),
	)
	changed, err := golang.Fix(root)
	if err != nil {
		t.Fatalf(
			"Fix() error = %v",
			err,
		)
	}

	if !slices.Equal(
		changed,
		[]string{"join.go", "join_test.go"},
	) {
		t.Errorf(
			"Fix() changed = %v, want join.go and join_test.go only",
			changed,
		)
	}

	fixed := readFile(
		t,
		filepath.Join(
			root,
			"join.go",
		),
	)
	assertSameSyntax(
		t,
		original,
		fixed,
	)
	assertNoLayoutFindings(
		t,
		root,
	)
}

func TestFixIsIdempotent(
	t *testing.T,
) {
	root := fixModule(t)
	_, err := golang.Fix(root)
	if err != nil {
		t.Fatalf(
			"first Fix() error = %v",
			err,
		)
	}

	changed, err := golang.Fix(root)
	isChanged := err != nil || len(changed) > 0
	if isChanged {
		t.Errorf(
			"second Fix() = %v, %v, want no change",
			changed,
			err,
		)
	}
}

func TestFixRejectsUnparsableModules(
	t *testing.T,
) {
	root := t.TempDir()
	writeFile(
		t,
		filepath.Join(
			root,
			"broken.go",
		),
		"package\n",
	)
	_, err := golang.Fix(root)
	if err == nil {
		t.Error("Fix() error = nil, want a parse error")
	}
}

func fixModule(
	t *testing.T,
) (root string) {
	t.Helper()
	root = t.TempDir()
	files := map[string]string{
		"go.mod":       "module example.com/fixture\n\ngo 1.24\n",
		"join.go":      kitchenSink,
		"join_test.go": "package fixture\n\nimport \"testing\"\n\nfunc TestJoin(t *testing.T) {\n\tif Join(1, 2) == \"\" {\n\t\tt.Error(\"empty\")\n\t}\n}\n",
		"gen.go":       "// Code generated by hand. DO NOT EDIT.\n\npackage fixture\n\nfunc gen(a int, b int) {}\n",
	}
	for name, content := range files {
		writeFile(
			t,
			filepath.Join(
				root,
				name,
			),
			content,
		)
	}

	return root
}

func assertSameSyntax(
	t *testing.T,
	original string,
	fixed string,
) {
	t.Helper()
	if syntaxDump(
		t,
		original,
	) != syntaxDump(
		t,
		fixed,
	) {
		t.Errorf(
			"Fix() changed more than positions:\n%s",
			fixed,
		)
	}
}

func syntaxDump(
	t *testing.T,
	content string,
) (dump string) {
	t.Helper()
	syntax, err := parser.ParseFile(
		token.NewFileSet(),
		"join.go",
		content,
		parser.ParseComments|parser.SkipObjectResolution,
	)
	if err != nil {
		t.Fatalf(
			"parse: %v",
			err,
		)
	}

	printed := strings.Builder{}
	err = ast.Fprint(
		&printed,
		nil,
		syntax,
		withoutPositions,
	)
	if err != nil {
		t.Fatalf(
			"print syntax: %v",
			err,
		)
	}

	return printed.String()
}

func withoutPositions(
	name string,
	value reflect.Value,
) (kept bool) {
	return value.Type() != reflect.TypeFor[token.Pos]() && ast.NotNilFilter(
		name,
		value,
	)
}

func assertNoLayoutFindings(
	t *testing.T,
	root string,
) {
	t.Helper()
	findings, err := golang.Golang(root)
	if err != nil {
		t.Fatalf(
			"Golang() error = %v",
			err,
		)
	}

	remaining := slices.DeleteFunc(
		ruleIDs(findings),
		isNotLayoutRule,
	)
	if len(remaining) > 0 {
		t.Errorf(
			"Golang() after Fix() still reports %v",
			remaining,
		)
	}
}

func isNotLayoutRule(
	rule string,
) (other bool) {
	return !slices.Contains(
		[]string{"R01", "R52", "R55"},
		rule,
	)
}

func readFile(
	t *testing.T,
	path string,
) (content string) {
	t.Helper()
	bytes, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf(
			"read %s: %v",
			path,
			err,
		)
	}

	return string(bytes)
}

func assertContains(
	t *testing.T,
	got []string,
	want string,
) {
	t.Helper()
	if !slices.Contains(
		got,
		want,
	) {
		t.Errorf(
			"Golang() rules = %v, want %s among them",
			got,
			want,
		)
	}
}

func assertGolangError(
	t *testing.T,
	root string,
	path string,
) {
	t.Helper()
	t.Setenv(
		"PATH",
		path,
	)
	_, err := golang.Golang(root)
	if err == nil {
		t.Errorf(
			"Golang(%s) with PATH %s: error = nil, want one",
			root,
			path,
		)
	}
}

func ruleIDs(
	findings []report.Finding,
) (ids []string) {
	for _, finding := range findings {
		ids = append(
			ids,
			finding.Rule,
		)
	}

	return ids
}

func writeFile(
	t *testing.T,
	path string,
	content string,
) {
	t.Helper()
	err := os.WriteFile(
		path,
		[]byte(content),
		0o600,
	)
	if err != nil {
		t.Fatalf(
			"write %s: %v",
			path,
			err,
		)
	}
}

