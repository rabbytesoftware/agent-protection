package source

import (
	"cmp"
	"go/ast"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	generatorPattern   = `^// Code generated by "?([^\s";,]+)`
	versionPattern     = `^v[0-9]+$`
	versionSeparator   = "@"
	goModFile          = "go.mod"
	entDirectory       = "ent"
	entSchemaDirectory = "schema"
	protocPluginPrefix = "protoc-gen-"
	protocTool         = "protoc"
	bufTool            = "buf"
	sqlcTool           = "sqlc"
	mockeryTool        = "mockery"
	mockgenTool        = "mockgen"
	stringerTool       = "stringer"
	parentDirectory    = ".."
)

func generatorOf(
	comments []*ast.Comment,
) (tool string) {
	for _, comment := range comments {
		tool = cmp.Or(
			tool,
			commentGenerator(comment.Text),
		)
	}

	return tool
}

func commentGenerator(
	text string,
) (tool string) {
	match := regexp.MustCompile(generatorPattern).FindStringSubmatch(text)
	isNamed := match != nil && regexp.MustCompile(generatedMarker).MatchString(text)
	if !isNamed {
		return ""
	}

	return toolName(strings.TrimRight(
		match[1],
		".",
	))
}

func toolName(
	reference string,
) (name string) {
	segments := strings.Split(
		strings.Split(
			reference,
			versionSeparator,
		)[0],
		"/",
	)
	last := len(segments) - 1
	isVersion := last > 0 && regexp.MustCompile(versionPattern).MatchString(segments[last])
	if isVersion {
		last--
	}

	return strings.ToLower(segments[last])
}

func isProven(
	path string,
	tool string,
) (proven bool) {
	if strings.HasPrefix(
		tool,
		protocPluginPrefix,
	) {
		return isProtobufOutput(path)
	}

	prover, known := provers()[tool]
	return known && prover(path)
}

func provers() (byTool map[string]func(string) bool) {
	return map[string]func(string) bool{
		protocTool:   isProtobufOutput,
		bufTool:      isProtobufOutput,
		sqlcTool:     isSqlcOutput,
		mockeryTool:  isMockeryOutput,
		mockgenTool:  isMockgenOutput,
		stringerTool: isStringerOutput,
		entDirectory: isEntOutput,
	}
}

func isSqlcOutput(
	path string,
) (proven bool) {
	return slices.ContainsFunc(
		configPaths(
			path,
			sqlcConfigs(),
		),
		coversDirectoryOf(path),
	)
}

func isProtobufOutput(
	path string,
) (proven bool) {
	isNamed := slices.ContainsFunc(
		protobufSuffixes(),
		isSuffixOf(path),
	)
	return isNamed && (slices.ContainsFunc(
		configPaths(
			path,
			bufConfigs(),
		),
		coversDirectoryOf(path),
	) || invokesAny(
		path,
		ancestors(filepath.Dir(path)),
		[]string{protocTool, bufTool},
	))
}

func isMockeryOutput(
	path string,
) (proven bool) {
	return isMockLocation(path) && (slices.ContainsFunc(
		configPaths(
			path,
			mockeryConfigs(),
		),
		isNonEmptyFile,
	) || invokesAny(
		path,
		ancestors(filepath.Dir(path)),
		[]string{mockeryTool},
	))
}

func isMockgenOutput(
	path string,
) (proven bool) {
	return isMockLocation(path) && invokesAny(
		path,
		ancestors(filepath.Dir(path)),
		[]string{mockgenTool},
	)
}

func isEntOutput(
	path string,
) (proven bool) {
	directory := filepath.Dir(path)
	for _, ancestor := range ancestors(directory) {
		proven = proven || isEntTree(
			ancestor,
			directory,
		)
	}

	return proven
}

func isEntTree(
	ancestor string,
	directory string,
) (isTree bool) {
	schema := filepath.Join(
		ancestor,
		entSchemaDirectory,
	)
	hasSchema, err := HasSource(schema)
	return filepath.Base(ancestor) == entDirectory && err == nil && hasSchema && !isWithin(
		schema,
		directory,
	)
}

func isMockLocation(
	path string,
) (isMockFile bool) {
	rel, err := filepath.Rel(
		moduleRoot(filepath.Dir(path)),
		path,
	)
	return err == nil && (IsMock(rel) || IsTest(path))
}

func configPaths(
	path string,
	names []string,
) (paths []string) {
	for _, ancestor := range ancestors(filepath.Dir(path)) {
		paths = append(
			paths,
			joined(
				ancestor,
				names,
			)...,
		)
	}

	return paths
}

func joined(
	directory string,
	names []string,
) (paths []string) {
	for _, name := range names {
		paths = append(
			paths,
			filepath.Join(
				directory,
				name,
			),
		)
	}

	return paths
}

func coversDirectoryOf(
	path string,
) (covers func(string) bool) {
	return func(
		config string,
	) (covered bool) {
		return slices.ContainsFunc(
			configOutputs(config),
			containsDirectoryOf(path),
		)
	}
}

func containsDirectoryOf(
	path string,
) (contains func(string) bool) {
	return func(
		output string,
	) (contained bool) {
		return isWithin(
			output,
			filepath.Dir(path),
		)
	}
}

func configOutputs(
	config string,
) (outputs []string) {
	content, err := os.ReadFile(config)
	var document any
	isParsed := err == nil && yaml.Unmarshal(
		content,
		&document,
	) == nil
	if !isParsed {
		return nil
	}

	return joined(
		filepath.Dir(config),
		outputPaths(document),
	)
}

func outputPaths(
	node any,
) (paths []string) {
	switch value := node.(type) {
	case map[string]any:
		return mappingOutputs(value)
	case []any:
		return sequenceOutputs(value)
	}

	return nil
}

func sequenceOutputs(
	sequence []any,
) (paths []string) {
	for _, item := range sequence {
		paths = append(
			paths,
			outputPaths(item)...,
		)
	}

	return paths
}

func mappingOutputs(
	mapping map[string]any,
) (paths []string) {
	for key, value := range mapping {
		paths = slices.Concat(
			paths,
			outputPaths(value),
			keyedOutput(
				key,
				value,
			),
		)
	}

	return paths
}

func keyedOutput(
	key string,
	value any,
) (paths []string) {
	text, isText := value.(string)
	isOutput := isText && slices.Contains(
		outputKeys(),
		key,
	)
	if !isOutput {
		return nil
	}

	return []string{text}
}

func isWithin(
	parent string,
	directory string,
) (within bool) {
	rel, err := filepath.Rel(
		filepath.Clean(parent),
		filepath.Clean(directory),
	)
	return err == nil && rel != parentDirectory && !strings.HasPrefix(
		rel,
		parentDirectory+string(filepath.Separator),
	)
}

func isSuffixOf(
	path string,
) (matches func(string) bool) {
	return func(
		suffix string,
	) (hasSuffix bool) {
		return strings.HasSuffix(
			path,
			suffix,
		)
	}
}

func ancestors(
	directory string,
) (chain []string) {
	chain = []string{directory}
	parent := filepath.Dir(directory)
	isLast := exists(filepath.Join(
		directory,
		goModFile,
	)) || parent == directory
	if isLast {
		return chain
	}

	return append(
		chain,
		ancestors(parent)...,
	)
}

func moduleRoot(
	directory string,
) (root string) {
	chain := ancestors(directory)
	return chain[len(chain)-1]
}

func exists(
	path string,
) (present bool) {
	_, err := os.Stat(path)
	return err == nil
}

func isNonEmptyFile(
	path string,
) (nonEmpty bool) {
	info, err := os.Stat(path)
	return err == nil && info.Mode().IsRegular() && info.Size() > 0
}

func outputKeys() (keys []string) {
	return []string{"out", "path"}
}

func protobufSuffixes() (suffixes []string) {
	return []string{".pb.go", ".pb.gw.go", ".connect.go"}
}

func sqlcConfigs() (names []string) {
	return []string{"sqlc.yaml", "sqlc.yml", "sqlc.json"}
}

func bufConfigs() (names []string) {
	return []string{"buf.gen.yaml", "buf.gen.yml"}
}

func mockeryConfigs() (names []string) {
	return []string{".mockery.yaml", ".mockery.yml"}
}
