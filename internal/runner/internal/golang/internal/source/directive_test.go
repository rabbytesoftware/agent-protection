package source_test

import "testing"

const stringerHeader = "// Code generated by \"stringer -type=Pill\"; DO NOT EDIT.\n\npackage pill\n"

func TestIsGeneratedReadsGenerateDirectives(
	t *testing.T,
) {
	cases := []struct {
		name   string
		files  map[string]string
		target string
		want   bool
	}{
		{name: "a stringer header named after a declared type is generated", files: map[string]string{"go.mod": goMod, "pill/pill.go": "package pill\n\n//go:generate stringer -type=Pill\ntype Pill int\n", "pill/pill_string.go": stringerHeader}, target: "pill/pill_string.go", want: true},
		{name: "a stringer -type given as a separate argument proves it", files: map[string]string{"go.mod": goMod, "pill/pill.go": "package pill\n\n//go:generate go tool stringer -type Color,Pill\ntype Pill int\n", "pill/pill_string.go": stringerHeader}, target: "pill/pill_string.go", want: true},
		{name: "a stringer header in a file not named after the type is hand-written", files: map[string]string{"go.mod": goMod, "pill/pill.go": "package pill\n\n//go:generate stringer -type=Pill\ntype Pill int\n", "pill/logic.go": stringerHeader}, target: "pill/logic.go", want: false},
		{name: "a stringer -type naming no declared type is hand-written", files: map[string]string{"go.mod": goMod, "pill/doc.go": "package pill\n\n//go:generate stringer -type=Pill\n", "pill/pill_string.go": stringerHeader + "\ntype Pill int\n"}, target: "pill/pill_string.go", want: false},
		{name: "a bare go run without a tool proves nothing", files: map[string]string{"go.mod": goMod, "pill/pill.go": "package pill\n\n//go:generate go run -mod=mod\ntype Pill int\n", "pill/pill_string.go": stringerHeader}, target: "pill/pill_string.go", want: false},
		{name: "an unparsable sibling declares no type", files: map[string]string{"go.mod": goMod, "pill/pill.go": "package pill\n\n//go:generate stringer -type=Pill\ntype Pill int\n", "pill/broken.go": "package\n", "pill/pill_string.go": stringerHeader}, target: "pill/pill_string.go", want: true},
	}
	for _, tc := range cases {
		assertProvenance(
			t,
			tc.files,
			tc.target,
			tc.want,
		)
	}
}
