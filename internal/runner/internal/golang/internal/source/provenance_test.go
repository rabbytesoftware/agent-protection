package source_test

import (
	"path/filepath"
	"testing"
)

const (
	sqlcHeader    = "// Code generated by sqlc. DO NOT EDIT.\n\npackage db\n"
	protocHeader  = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage pb\n"
	mockeryHeader = "// Code generated by mockery v2.42.0. DO NOT EDIT.\n\npackage mocks\n"
	mockgenHeader = "// Code generated by MockGen. DO NOT EDIT.\n\npackage mocks\n"
	entHeader     = "// Code generated by ent, DO NOT EDIT.\n\npackage ent\n"
	goMod         = "module m\n"
	sqlcConfig    = "version: \"2\"\nsql:\n  - engine: postgresql\n    queries: query.sql\n    gen:\n      go:\n        out: internal/db\n"
)

func TestIsGeneratedNeedsMatchingProvenance(
	t *testing.T,
) {
	cases := []struct {
		name   string
		files  map[string]string
		target string
		want   bool
	}{
		{name: "a header alone is hand-written", files: map[string]string{"go.mod": goMod, "internal/db/q.go": sqlcHeader}, target: "internal/db/q.go", want: false},
		{name: "an sqlc header under the configured out path is generated", files: map[string]string{"go.mod": goMod, "sqlc.yaml": sqlcConfig, "internal/db/q.go": sqlcHeader}, target: "internal/db/q.go", want: true},
		{name: "a v1 sqlc json config with a package path proves it", files: map[string]string{"go.mod": goMod, "sqlc.json": "{\"version\": \"1\", \"packages\": [{\"path\": \"internal/db\"}]}", "internal/db/q.go": sqlcHeader}, target: "internal/db/q.go", want: true},
		{name: "a one-line sqlc config proves nothing", files: map[string]string{"go.mod": goMod, "sqlc.yaml": "version: \"2\"\n", "internal/db/q.go": sqlcHeader}, target: "internal/db/q.go", want: false},
		{name: "an sqlc header outside the configured out path is hand-written", files: map[string]string{"go.mod": goMod, "sqlc.yaml": sqlcConfig, "internal/square/q.go": sqlcHeader}, target: "internal/square/q.go", want: false},
		{name: "an unparsable sqlc config proves nothing", files: map[string]string{"go.mod": goMod, "sqlc.yaml": "out: [\n", "internal/db/q.go": sqlcHeader}, target: "internal/db/q.go", want: false},
		{name: "an sqlc config above the module root is ignored", files: map[string]string{"sqlc.yaml": "version: \"2\"\nsql:\n  - gen:\n      go:\n        out: m/internal/db\n", "m/go.mod": goMod, "m/internal/db/q.go": sqlcHeader}, target: "m/internal/db/q.go", want: false},
		{name: "a protoc header in a .pb.go file under a buf out path is generated", files: map[string]string{"go.mod": goMod, "buf.gen.yaml": "version: v2\nplugins:\n  - local: protoc-gen-go\n    out: gen\n", "gen/api/v1/api.pb.go": protocHeader}, target: "gen/api/v1/api.pb.go", want: true},
		{name: "a protoc header proven by a go:generate protoc is generated", files: map[string]string{"go.mod": goMod, "pb/gen.go": "package pb\n\n//go:generate protoc --go_out=. api.proto\n", "pb/api_grpc.pb.go": "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n\npackage pb\n"}, target: "pb/api_grpc.pb.go", want: true},
		{name: "a protoc header in a file not named .pb.go is hand-written", files: map[string]string{"go.mod": goMod, "buf.gen.yaml": "version: v2\nplugins:\n  - local: protoc-gen-go\n    out: gen\n", "gen/api.go": protocHeader}, target: "gen/api.go", want: false},
		{name: "a protoc header with only an unrelated go:generate is hand-written", files: map[string]string{"go.mod": goMod, "pb/gen.go": "package pb\n\n//go:generate go run ./tool\n", "pb/api.pb.go": protocHeader}, target: "pb/api.pb.go", want: false},
		{name: "a mockery header in a mocks directory with a mockery config is generated", files: map[string]string{"go.mod": goMod, ".mockery.yaml": "with-expecter: true\n", "mocks/store.go": mockeryHeader}, target: "mocks/store.go", want: true},
		{name: "a mockery header proven by go run of mockery is generated", files: map[string]string{"go.mod": goMod, "doc.go": "package m\n\n//go:generate go run github.com/vektra/mockery/v2@v2.42.0\n", "mocks/store.go": mockeryHeader}, target: "mocks/store.go", want: true},
		{name: "a mockery header outside a mock location is hand-written", files: map[string]string{"go.mod": goMod, ".mockery.yaml": "with-expecter: true\n", "store/store.go": mockeryHeader}, target: "store/store.go", want: false},
		{name: "a mockgen header in a mock file with a go:generate mockgen is generated", files: map[string]string{"go.mod": goMod, "store/store.go": "package store\n\n//go:generate go run go.uber.org/mock/mockgen -destination=mock_store.go . Store\n", "store/mock_store.go": mockgenHeader}, target: "store/mock_store.go", want: true},
		{name: "a mockgen header without a go:generate mockgen is hand-written", files: map[string]string{"go.mod": goMod, "store/store.go": "package store\n\n//go:generate mockery\n", "store/mock_store.go": mockgenHeader}, target: "store/mock_store.go", want: false},
		{name: "an ent header inside the ent tree with a schema is generated", files: map[string]string{"go.mod": goMod, "ent/schema/user.go": "package schema\n", "ent/user/user.go": entHeader}, target: "ent/user/user.go", want: true},
		{name: "an ent header outside the ent tree is hand-written", files: map[string]string{"go.mod": goMod, "ent/schema/user.go": "package schema\n", "billing/user.go": entHeader}, target: "billing/user.go", want: false},
		{name: "an ent header inside the schema is hand-written", files: map[string]string{"go.mod": goMod, "ent/schema/user.go": "package schema\n", "ent/schema/gen.go": entHeader}, target: "ent/schema/gen.go", want: false},
		{name: "an unknown generator is hand-written even with a matching go:generate", files: map[string]string{"go.mod": goMod, "doc.go": "package m\n\n//go:generate squaregen\n", "gen.go": "// Code generated by squaregen. DO NOT EDIT.\n\npackage m\n"}, target: "gen.go", want: false},
		{name: "a header without a generator name is hand-written", files: map[string]string{"go.mod": goMod, "sqlc.yaml": sqlcConfig, "internal/db/q.go": "// Code generated automatically. DO NOT EDIT.\n\npackage db\n"}, target: "internal/db/q.go", want: false},
	}
	for _, tc := range cases {
		assertProvenance(
			t,
			tc.files,
			tc.target,
			tc.want,
		)
	}
}

func assertProvenance(
	t *testing.T,
	files map[string]string,
	target string,
	want bool,
) {
	t.Helper()
	root := t.TempDir()
	writeFiles(
		t,
		root,
		files,
	)
	assertGenerated(
		t,
		filepath.Join(
			root,
			target,
		),
		want,
	)
}
