func TestSourceReportsUnparsableFiles(
	t *testing.T,
) {
	root := t.TempDir()
	writeFile(
		t,
		filepath.Join(
			root,
			"broken.go",
		),
		"package\n",
	)
	_, err := source.Source(root)
	if err == nil {
		t.Error("Source() error = nil, want a parse error")
	}
}

func TestSourceReportsUnreadableFiles(
	t *testing.T,
) {
	root := t.TempDir()
	path := filepath.Join(
		root,
		"locked.go",
	)
	writeFile(
		t,
		path,
		"package locked\n",
	)
	err := os.Chmod(
		path,
		0,
	)
	if err != nil {
		t.Fatalf(
			"chmod: %v",
			err,
		)
	}

	_, err = source.Source(root)
	if err == nil {
		t.Error("Source() error = nil, want a read error")
	}
}

func TestParse(
	t *testing.T,
) {
	content := []byte("package p\n")
	file, err := source.Parse(
		"root",
		"root/dir/p.go",
		content,
	)
	if err != nil {
		t.Fatalf(
			"Parse() error = %v",
			err,
		)
	}

	isMismatch := file.Rel != "dir/p.go" || string(file.Content) != string(content)
	if isMismatch {
		t.Errorf(
			"Parse() = Rel %q Content %q, want dir/p.go and the parsed content",
			file.Rel,
			file.Content,
		)
	}

	_, err = source.Parse(
		"root",
		"root/dir/p.go",
		[]byte("package\n"),
	)
	if err == nil {
		t.Error("Parse() error = nil, want a parse error")
	}
}

func TestRelPath(
	t *testing.T,
) {
	cases := []struct {
		root string
		path string
		want string
	}{
		{root: "/repo", path: "/repo/internal/a.go", want: "internal/a.go"},
		{root: "/repo", path: "relative/a.go", want: "relative/a.go"},
	}
	for _, tc := range cases {
		assertRelPath(
			t,
			tc.root,
			tc.path,
			tc.want,
		)
	}
}

func TestWalkersRejectMissingRoot(
	t *testing.T,
) {
	missing := filepath.Join(
		t.TempDir(),
		"missing",
	)
	walkers := []func(string) error{
		sourceError,
		testsError,
		pathsError,
		directoriesError,
	}
	for _, walker := range walkers {
		assertWalkError(
			t,
			walker,
			missing,
		)
	}
}

func assertRelPath(
	t *testing.T,
	root string,
	path string,
	want string,
) {
	t.Helper()
	rel := source.RelPath(
		root,
		path,
	)
	if rel != want {
		t.Errorf(
			"RelPath(%q, %q) = %q, want %q",
			root,
			path,
			rel,
			want,
		)
	}
}

func assertWalkError(
	t *testing.T,
	walker func(string) error,
	root string,
) {
	t.Helper()
	err := walker(root)
	if err == nil {
		t.Errorf(
			"walking missing root %s: error = nil, want one",
			root,
		)
	}
}

func sourceError(
	root string,
) (err error) {
	_, err = source.Source(root)
	return err
}

func testsError(
	root string,
) (err error) {
	_, err = source.Tests(root)
	return err
}

func pathsError(
	root string,
) (err error) {
	_, err = source.Paths(root)
	return err
}

func directoriesError(
	root string,
) (err error) {
	_, err = source.Directories(root)
	return err
}

func TestIsGenerated(
	t *testing.T,
) {
	root := fixtureModule(t)
	cases := map[string]bool{"pkg/gen.go": true, "pkg/a.go": false, "missing.go": false}
	for path, want := range cases {
		assertGenerated(
			t,
			filepath.Join(
				root,
				path,
			),
			want,
		)
	}
}

func assertGenerated(
	t *testing.T,
	path string,
	want bool,
) {
	t.Helper()
	got := source.IsGenerated(path)
	if got != want {
		t.Errorf(
			"IsGenerated(%s) = %v, want %v",
			path,
			got,
			want,
		)
	}
}

func fixtureModule(
	t *testing.T,
) (root string) {
	t.Helper()
	root = t.TempDir()
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/a.go",
		),
		"package pkg\n",
	)
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/a_test.go",
		),
		"package pkg\n",
	)
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/gen.go",
		),
		"// Code generated by tool. DO NOT EDIT.\n\npackage pkg\n",
	)
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/it_test.go",
		),
		"//go:build integration\n\npackage pkg\n",
	)
	return root
}

func relPaths(
	files []source.File,
) (paths []string) {
	for _, file := range files {
		paths = append(
			paths,
			file.Rel,
		)
	}
	return paths
}
