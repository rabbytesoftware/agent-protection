package source_test

import (
	"path/filepath"
	"slices"
	"testing"

	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/golang/internal/source"
)

func TestSource(
	t *testing.T,
) {
	root := fixtureModule(t)
	files, err := source.Source(root)
	if err != nil {
		t.Fatalf(
			"Source() error = %v",
			err,
		)
	}
	got := relPaths(files)
	if !slices.Equal(
		got,
		[]string{"pkg/a.go"},
	) {
		t.Errorf(
			"Source() = %v, want only the hand-written source file",
			got,
		)
	}
}

func TestTests(
	t *testing.T,
) {
	root := fixtureModule(t)
	files, err := source.Tests(root)
	if err != nil {
		t.Fatalf(
			"Tests() error = %v",
			err,
		)
	}
	got := relPaths(files)
	if !slices.Equal(
		got,
		[]string{"pkg/a_test.go"},
	) {
		t.Errorf(
			"Tests() = %v, want only the unit test file",
			got,
		)
	}
}

func TestPaths(
	t *testing.T,
) {
	root := fixtureModule(t)
	paths, err := source.Paths(root)
	if err != nil {
		t.Fatalf(
			"Paths() error = %v",
			err,
		)
	}
	want := []string{filepath.Join(
		root,
		"pkg/a.go",
	), filepath.Join(
		root,
		"pkg/gen.go",
	)}
	if !slices.Equal(
		paths,
		want,
	) {
		t.Errorf(
			"Paths() = %v, want %v",
			paths,
			want,
		)
	}
}

func TestSourceReportsUnparsableFiles(
	t *testing.T,
) {
	root := t.TempDir()
	writeFile(
		t,
		filepath.Join(
			root,
			"broken.go",
		),
		"package\n",
	)
	_, err := source.Source(root)
	if err == nil {
		t.Error("Source() error = nil, want a parse error")
	}
}

func TestRelPath(
	t *testing.T,
) {
	rel := source.RelPath(
		"/repo",
		"/repo/internal/a.go",
	)
	if rel != "internal/a.go" {
		t.Errorf(
			"RelPath() = %q, want internal/a.go",
			rel,
		)
	}
}

func TestIsGenerated(
	t *testing.T,
) {
	root := fixtureModule(t)
	cases := map[string]bool{"pkg/gen.go": true, "pkg/a.go": false, "missing.go": false}
	for path, want := range cases {
		assertGenerated(
			t,
			filepath.Join(
				root,
				path,
			),
			want,
		)
	}
}

func assertGenerated(
	t *testing.T,
	path string,
	want bool,
) {
	t.Helper()
	got := source.IsGenerated(path)
	if got != want {
		t.Errorf(
			"IsGenerated(%s) = %v, want %v",
			path,
			got,
			want,
		)
	}
}

func fixtureModule(
	t *testing.T,
) (root string) {
	t.Helper()
	root = t.TempDir()
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/a.go",
		),
		"package pkg\n",
	)
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/a_test.go",
		),
		"package pkg\n",
	)
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/gen.go",
		),
		"// Code generated by tool. DO NOT EDIT.\n\npackage pkg\n",
	)
	writeFile(
		t,
		filepath.Join(
			root,
			"pkg/it_test.go",
		),
		"//go:build integration\n\npackage pkg\n",
	)
	return root
}

func relPaths(
	files []source.File,
) (paths []string) {
	for _, file := range files {
		paths = append(
			paths,
			file.Rel,
		)
	}
	return paths
}
