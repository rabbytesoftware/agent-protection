func TestSource(
	t *testing.T,
) {
	root := fixtureModule(t)
	files, err := source.Source(root)
	if err != nil {
		t.Fatalf(
			"Source() error = %v",
			err,
		)
	}
	got := relPaths(files)
	if !slices.Equal(
		got,
		[]string{"pkg/a.go"},
	) {
		t.Errorf(
			"Source() = %v, want only the hand-written source file",
			got,
		)
	}
}

