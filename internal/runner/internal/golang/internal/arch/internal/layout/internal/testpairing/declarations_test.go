package testpairing_test

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/golang/internal/arch/internal/layout/internal/testpairing"
)

const noTests = "package x_test\n\nimport \"testing\"\n\nfunc helper(t *testing.T) {}\n\nfunc Testify() {}\n"

func TestTestpairingDeclarations(
	t *testing.T,
) {
	cases := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{
			name:  "source holding no declarations is reported as empty",
			files: map[string]string{"x/flows.go": "package x\n\nimport _ \"embed\"\n", "x/flows_test.go": unitTest},
			want:  []string{"R42 x/flows.go"},
		},
		{
			name:  "generated source holding no declarations is not reported",
			files: map[string]string{"x/gen.go": "// Code generated by tool. DO NOT EDIT.\n\npackage x\n"},
			want:  nil,
		},
		{
			name:  "paired test declaring no test functions is reported",
			files: map[string]string{"x/a.go": behavior, "x/a_test.go": noTests},
			want:  []string{"R42 x/a_test.go"},
		},
		{
			name:  "paired test with only a benchmark, fuzz target or example passes",
			files: map[string]string{"x/a.go": behavior, "x/a_test.go": "package x\n\nfunc BenchmarkA() {}\n", "x/b.go": behavior, "x/b_test.go": "package x\n\nfunc FuzzB() {}\n", "x/c.go": behavior, "x/c_test.go": "package x\n\nfunc Example() {}\n"},
			want:  nil,
		},
	}
	for _, tc := range cases {
		assertFindings(
			t,
			tc.name,
			checked(
				t,
				tc.files,
			),
			tc.want,
		)
	}
}

func TestTestpairingRejectsUnparsableTests(
	t *testing.T,
) {
	_, err := testpairing.Testpairing(module(
		t,
		map[string]string{"x/a.go": behavior, "x/a_test.go": "package x\n\nfunc {\n"},
	))
	if err == nil {
		t.Error("Testpairing() error = nil, want one for an unparsable test file")
	}
}

func TestTestpairingRejectsUnreadableFiles(
	t *testing.T,
) {
	for _, locked := range []string{"x/a.go", "x/a_test.go"} {
		assertUnreadableRejected(
			t,
			locked,
		)
	}
}

func assertUnreadableRejected(
	t *testing.T,
	locked string,
) {
	t.Helper()
	_, err := testpairing.Testpairing(lockedModule(
		t,
		locked,
	))
	if err == nil {
		t.Errorf(
			"Testpairing() error = nil, want one for unreadable %s",
			locked,
		)
	}
}

func lockedModule(
	t *testing.T,
	locked string,
) (root string) {
	t.Helper()
	root = module(
		t,
		map[string]string{"x/a.go": behavior, "x/a_test.go": unitTest},
	)
	err := os.Chmod(
		filepath.Join(
			root,
			locked,
		),
		0,
	)
	if err != nil {
		t.Fatalf(
			"chmod: %v",
			err,
		)
	}

	return root
}
