package testpairing_test

import (
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/rabbytesoftware/agent-protection/internal/report"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/golang/internal/arch/internal/testpairing"
)

const (
	behavior = "package x\n\nfunc A() {}\n"
	unitTest = "package x_test\n"
)

func TestTestpairing(
	t *testing.T,
) {
	cases := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{
			name:  "source with its test passes",
			files: map[string]string{"x/a.go": behavior, "x/a_test.go": unitTest},
			want:  nil,
		},
		{
			name:  "source without a test is reported",
			files: map[string]string{"x/a.go": behavior},
			want:  []string{"R42 x/a.go"},
		},
		{
			name:  "declaration-only source needs no test",
			files: map[string]string{"x/types.go": "package x\n\ntype Rule struct {\n\tID string\n}\n\nvar Registry = map[string]Rule{}\n"},
			want:  nil,
		},
		{
			name:  "mock source needs no test, in a mocks directory or by name",
			files: map[string]string{"x/mocks/bus.go": behavior, "x/fake_clock.go": behavior},
			want:  nil,
		},
		{
			name:  "generated source needs no test",
			files: map[string]string{"x/gen.go": "// Code generated by tool. DO NOT EDIT.\n\npackage x\n\nfunc B() {}\n"},
			want:  nil,
		},
		{
			name:  "test without its source is reported",
			files: map[string]string{"x/a.go": behavior, "x/a_test.go": unitTest, "x/misc_test.go": unitTest},
			want:  []string{"R43 x/misc_test.go"},
		},
		{
			name:  "benchmark and integration test files pair with their source",
			files: map[string]string{"x/a.go": behavior, "x/a_test.go": unitTest, "x/a_bench_test.go": unitTest, "x/a_integration_test.go": unitTest},
			want:  nil,
		},
		{
			name:  "benchmark test without its source is reported",
			files: map[string]string{"x/a_bench_test.go": unitTest},
			want:  []string{"R43 x/a_bench_test.go"},
		},
		{
			name:  "integration test without its source is reported",
			files: map[string]string{"x/integration_test.go": "//go:build integration\n\npackage x_test\n"},
			want:  []string{"R43 x/integration_test.go"},
		},
		{
			name:  "package main pairs like any other package",
			files: map[string]string{"cmd/app/main.go": "package main\n\nfunc main() {}\n", "cmd/app/main_test.go": "package main\n", "cmd/app/app_test.go": "package main\n"},
			want:  []string{"R43 cmd/app/app_test.go"},
		},
	}
	for _, tc := range cases {
		assertFindings(
			t,
			tc.name,
			checked(
				t,
				tc.files,
			),
			tc.want,
		)
	}
}

func checked(
	t *testing.T,
	files map[string]string,
) (findings []report.Finding) {
	t.Helper()
	findings, err := testpairing.Testpairing(module(
		t,
		files,
	))
	if err != nil {
		t.Fatalf(
			"Testpairing() error = %v",
			err,
		)
	}
	return findings
}

func module(
	t *testing.T,
	files map[string]string,
) (root string) {
	t.Helper()
	root = t.TempDir()
	for name, content := range files {
		write(
			t,
			filepath.Join(
				root,
				name,
			),
			content,
		)
	}
	return root
}

func write(
	t *testing.T,
	path string,
	content string,
) {
	t.Helper()
	err := os.MkdirAll(
		filepath.Dir(path),
		0o755,
	)
	if err != nil {
		t.Fatalf(
			"mkdir %s: %v",
			path,
			err,
		)
	}
	err = os.WriteFile(
		path,
		[]byte(content),
		0o600,
	)
	if err != nil {
		t.Fatalf(
			"write %s: %v",
			path,
			err,
		)
	}
}

func assertFindings(
	t *testing.T,
	name string,
	findings []report.Finding,
	want []string,
) {
	t.Helper()
	got := []string{}
	for _, finding := range findings {
		got = append(
			got,
			finding.Rule+" "+finding.Location,
		)
	}
	if !slices.Equal(
		got,
		want,
	) {
		t.Errorf(
			"%s: findings = %v, want %v",
			name,
			got,
			want,
		)
	}
}

func TestTestpairingRejectsMissingRoot(
	t *testing.T,
) {
	missing := filepath.Join(
		t.TempDir(),
		"missing",
	)
	_, err := testpairing.Testpairing(missing)
	if err == nil {
		t.Error("Testpairing() error = nil, want one for a missing root")
	}
}

func TestTestpairingRejectsUnparsableFiles(
	t *testing.T,
) {
	_, err := testpairing.Testpairing(module(
		t,
		map[string]string{"broken.go": "package p\n\nfunc {\n"},
	))
	if err == nil {
		t.Error("Testpairing() error = nil, want one for an unparsable source file")
	}
}
