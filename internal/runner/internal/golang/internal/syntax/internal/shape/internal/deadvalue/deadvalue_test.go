package deadvalue_test

import (
	"go/ast"
	"go/parser"
	"go/token"
	"maps"
	"slices"
	"testing"

	"github.com/rabbytesoftware/agent-protection/internal/report"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/golang/internal/source"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/golang/internal/syntax/internal/shape/internal/deadvalue"
)

type fixture struct {
	name  string
	files map[string]string
	want  []string
}

const deadSnippet = "const limit is declared and never read: delete it; a value nothing reads is dead code, and what it was meant to say belongs in names, structure or the commit message"

func TestDeadvalue(
	t *testing.T,
) {
	assertFixtures(
		t,
		[]fixture{
			{
				name:  "unreferenced unexported const is reported",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nconst limit = 3\n"},
				want:  []string{"R69 internal/cube/cube.go:3 " + deadSnippet},
			},
			{
				name:  "unreferenced unexported var is reported",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nvar cache map[string]int\n"},
				want:  []string{"R69 internal/cube/cube.go:3 var cache is declared and never read: delete it; a value nothing reads is dead code, and what it was meant to say belongs in names, structure or the commit message"},
			},
			{
				name:  "const read in another file of the package passes",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nconst limit = 3\n", "internal/cube/use.go": "package cube\n\nfunc Use() (n int) {\n\treturn limit\n}\n"},
				want:  nil,
			},
			{
				name:  "const read only by a test passes",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nconst limit = 3\n", "internal/cube/cube_test.go": "package cube\n\nvar seen = limit\n"},
				want:  nil,
			},
			{
				name:  "a same-named const in another package does not count as a read",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nconst limit = 3\n", "internal/square/square.go": "package square\n\nconst limit = 2\n\nfunc Use() (n int) {\n\treturn limit\n}\n"},
				want:  []string{"R69 internal/cube/cube.go:3 " + deadSnippet},
			},
			{
				name:  "binding to blank is not a read",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nconst limit = 3\n\nvar _ = limit\n\nfunc f() {\n\t_ = limit\n}\n"},
				want:  []string{"R69 internal/cube/cube.go:3 " + deadSnippet},
			},
			{
				name:  "exported const in an internal package read through a selector passes",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nconst Limit = 3\n", "container.go": "package m\n\nimport \"example.com/m/internal/cube\"\n\nfunc New() (n int) {\n\treturn cube.Limit\n}\n"},
				want:  nil,
			},
			{
				name:  "exported const in an internal package nobody reads is reported",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nconst Limit = 3\n"},
				want:  []string{"R69 internal/cube/cube.go:3 const Limit is declared and never read: delete it; a value nothing reads is dead code, and what it was meant to say belongs in names, structure or the commit message"},
			},
			{
				name:  "exported const in a public package is API",
				files: map[string]string{"cube.go": "package cube\n\nconst Limit = 3\n\nconst Note = \"TODO: this is a public message for other modules\"\n"},
				want:  nil,
			},
			{
				name:  "iota enumerations are left alone",
				files: map[string]string{"internal/cube/state.go": "package cube\n\nconst (\n\tidle = iota\n\tbusy\n\tdone\n)\n"},
				want:  nil,
			},
			{
				name:  "unused local const is reported",
				files: map[string]string{"internal/cube/cube.go": "package cube\n\nfunc Run() (n int) {\n\tconst limit = 3\n\tconst used = 2\n\treturn used\n}\n"},
				want:  []string{"R69 internal/cube/cube.go:4 " + deadSnippet},
			},
			{
				name: "blank declarations, tests, mocks and generated files are not checked",
				files: map[string]string{
					"internal/cube/cube.go":    "package cube\n\nconst _ = 1\n\nfunc f() {}\n",
					"internal/cube/x_test.go":  "package cube\n\nconst limit = 3\n",
					"internal/cube/mocks/m.go": "package mocks\n\nconst limit = 3\n",
					"internal/cube/gen.go":     "// Code generated by tool. DO NOT EDIT.\n\npackage cube\n\nconst limit = 3\n",
				},
				want: nil,
			},
		},
	)
}

func assertFixtures(
	t *testing.T,
	fixtures []fixture,
) {
	t.Helper()
	for _, each := range fixtures {
		files := parsedFiles(
			t,
			each.files,
		)
		assertFindings(
			t,
			each.name,
			deadvalue.Deadvalue(
				files,
				files,
			),
			each.want,
		)
	}
}

func parsedFiles(
	t *testing.T,
	files map[string]string,
) (parsed []source.File) {
	t.Helper()
	for _, path := range slices.Sorted(maps.Keys(files)) {
		parsed = append(
			parsed,
			parsedFile(
				t,
				path,
				files[path],
			),
		)
	}

	return parsed
}

func parsedFile(
	t *testing.T,
	path string,
	code string,
) (file source.File) {
	t.Helper()
	fileSet := token.NewFileSet()
	syntax, err := parser.ParseFile(
		fileSet,
		path,
		code,
		parser.ParseComments,
	)
	if err != nil {
		t.Fatalf(
			"parse fixture %s: %v",
			path,
			err,
		)
	}

	return source.File{
		Path:        path,
		Rel:         path,
		FileSet:     fileSet,
		Syntax:      syntax,
		IsGenerated: ast.IsGenerated(syntax),
	}
}

func assertFindings(
	t *testing.T,
	name string,
	findings []report.Finding,
	want []string,
) {
	t.Helper()
	got := []string{}
	for _, finding := range findings {
		got = append(
			got,
			finding.Rule+" "+finding.Location+" "+finding.Snippet,
		)
	}

	isMismatch := !slices.Equal(
		got,
		want,
	) && len(got)+len(want) > 0
	if isMismatch {
		t.Errorf(
			"%s: findings = %v, want %v",
			name,
			got,
			want,
		)
	}
}
