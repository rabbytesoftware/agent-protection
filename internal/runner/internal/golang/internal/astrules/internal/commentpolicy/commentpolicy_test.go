package commentpolicy_test

import (
	"go/parser"
	"go/token"
	"slices"
	"testing"

	"github.com/rabbytesoftware/agent-protection/internal/report"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/golang/internal/astrules/internal/commentpolicy"
	"github.com/rabbytesoftware/agent-protection/internal/runner/internal/golang/internal/source"
)

func TestCommentpolicy(
	t *testing.T,
) {
	cases := []struct {
		name string
		path string
		code string
		want []string
	}{
		{
			name: "documented exported func passes",
			path: "p.go",
			code: `package p

// F does a thing.
func F() {
}
`,
			want: nil,
		},
		{
			name: "comment on an unexported func is reported",
			path: "p.go",
			code: `package p

// f does a thing.
func f() {
}
`,
			want: []string{"R07 p.go:3"},
		},
		{
			name: "package doc comment is reported",
			path: "p.go",
			code: `// Package p does things.
package p
`,
			want: []string{"R07 p.go:1"},
		},
		{
			name: "prose header before the package clause is reported",
			path: "p.go",
			code: `// Copyright the authors.

package p
`,
			want: []string{"R07 p.go:1"},
		},
		{
			name: "build constraint header passes",
			path: "p.go",
			code: `//go:build linux
// +build linux

package p
`,
			want: nil,
		},
		{
			name: "generated code header passes",
			path: "p.go",
			code: `// Code generated by stringer. DO NOT EDIT.

package p
`,
			want: nil,
		},
		{
			name: "trailing and body comments are reported",
			path: "p.go",
			code: `package p

// F does a thing.
func F() {
	work() // trailing
	// own line
	work()
}

func work() {
}
`,
			want: []string{"R07 p.go:5", "R07 p.go:6"},
		},
		{
			name: "floating comment between declarations is reported",
			path: "p.go",
			code: `package p

func f() {
}

// floating

func g() {
}
`,
			want: []string{"R07 p.go:6"},
		},
		{
			name: "methods follow their own name",
			path: "p.go",
			code: `package p

type t struct{}

// M is documented.
func (r t) M() {
}

func (r t) N() {
}

// m is not exported.
func (r t) m() {
}
`,
			want: []string{"R07 p.go:12", "R07 p.go:9"},
		},
		{
			name: "types follow their own name",
			path: "p.go",
			code: `package p

// T is documented.
type T struct{}

// t is not exported.
type t struct{}

type U struct{}
`,
			want: []string{"R07 p.go:6", "R07 p.go:9"},
		},
		{
			name: "grouped declaration doc covers its exported specs",
			path: "p.go",
			code: `package p

// Limits shared by every check.
const (
	A = 1
	B = 2
)
`,
			want: nil,
		},
		{
			name: "grouped specs are checked one by one",
			path: "p.go",
			code: `package p

const (
	// A is documented.
	A = 1
	// b is not exported.
	b = 2
	C = 3
)

var (
	d = 4
	// e is not exported.
	e = 5
)
`,
			want: []string{"R07 p.go:6", "R07 p.go:13", "R07 p.go:8"},
		},
		{
			name: "exported struct field docs pass and the rest are reported",
			path: "p.go",
			code: `package p

// T holds data.
type T struct {
	// Name is the display name.
	Name string
	// Base is embedded.
	Base
	// count is hidden.
	count int
	Size  int // trailing
}

// Base is embedded.
type Base struct{}
`,
			want: []string{"R07 p.go:9", "R07 p.go:11"},
		},
		{
			name: "embedded field docs follow the embedded type's export",
			path: "p.go",
			code: `package p

import "strings"

// T embeds several kinds of types.
type T struct {
	// Builder is exported through its selector.
	*strings.Builder
	// Pair is an exported generic.
	Pair[int, string]
	// List is an exported generic.
	List[int]
	// pair is an unexported generic.
	*pair[int, string]
}

// Pair holds two values.
type Pair[A any, B any] struct{}

// List holds values.
type List[A any] struct{}

type pair[A any, B any] struct{}
`,
			want: []string{"R07 p.go:13"},
		},
		{
			name: "exported interface method docs pass and the rest are reported",
			path: "p.go",
			code: `package p

// I does things.
type I interface {
	// Do does it.
	Do()
	// undo is hidden.
	undo()
}
`,
			want: []string{"R07 p.go:7"},
		},
		{
			name: "comments on parameters are reported",
			path: "p.go",
			code: `package p

// F does a thing.
func F(
	// Size is a parameter.
	Size int,
) {
}
`,
			want: []string{"R07 p.go:5"},
		},
		{
			name: "directives pass anywhere",
			path: "p.go",
			code: `package p

import "embed"

//go:generate stringer -type=T

//go:embed testdata
var files embed.FS

//go:noinline
func f() {
	//line other.go:10
	work()
}
`,
			want: nil,
		},
		{
			name: "nolint suppressions are reported even inside a doc comment",
			path: "p.go",
			code: `package p

// F does a thing.
//
//nolint:all
func F() {
	work() //nolint:errcheck
}
`,
			want: []string{"R07 p.go:3", "R07 p.go:7"},
		},
		{
			name: "deprecation notices and spec links pass anywhere",
			path: "p.go",
			code: `package p

// Deprecated: use g.
func f() {
	work() // https://go.dev/ref/spec#Comments
	/* see http://example.com/spec */
}
`,
			want: nil,
		},
		{
			name: "prose mixed with a spec link is reported",
			path: "p.go",
			code: `package p

// f follows the spec.
// https://go.dev/ref/spec
func f() {
}
`,
			want: []string{"R07 p.go:3"},
		},
		{
			name: "comment on a test function is reported",
			path: "p_test.go",
			code: `package p_test

import "testing"

// TestF checks F.
func TestF(
	t *testing.T,
) {
}
`,
			want: []string{"R07 p_test.go:5"},
		},
	}
	for _, tc := range cases {
		assertFindings(
			t,
			tc.name,
			commentpolicy.Commentpolicy([]source.File{parsed(
				t,
				tc.path,
				tc.code,
			)}),
			tc.want,
		)
	}
}

func parsed(
	t *testing.T,
	path string,
	code string,
) (file source.File) {
	t.Helper()
	fileSet := token.NewFileSet()
	syntax, err := parser.ParseFile(
		fileSet,
		path,
		code,
		parser.ParseComments,
	)
	if err != nil {
		t.Fatalf(
			"parse fixture: %v",
			err,
		)
	}
	return source.File{Path: path, Rel: path, FileSet: fileSet, Syntax: syntax}
}

func assertFindings(
	t *testing.T,
	name string,
	findings []report.Finding,
	want []string,
) {
	t.Helper()
	got := []string{}
	for _, finding := range findings {
		got = append(
			got,
			finding.Rule+" "+finding.Location,
		)
	}
	isMismatch := !slices.Equal(
		got,
		want,
	) && len(got)+len(want) > 0
	if isMismatch {
		t.Errorf(
			"%s: findings = %v, want %v",
			name,
			got,
			want,
		)
	}
}
