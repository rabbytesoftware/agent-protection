func TestWalkGoFiles_SkipsTestAndGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	write := func(name, content string) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}
	write("real.go", "package x\nfunc A() {}\n")
	write("real_test.go", "package x\nfunc TestA() {}\n")
	write("gen.go", "// Code generated by tool. DO NOT EDIT\npackage x\nfunc B() {}\n")

	files, err := WalkGoFiles(dir)
	if err != nil {
		t.Fatalf("WalkGoFiles: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("expected exactly 1 file (real.go), got %d: %v", len(files), files)
	}
	if filepath.Base(files[0].Path) != "real.go" {
		t.Fatalf("expected real.go, got %s", files[0].Path)
	}
}

func TestRelPath(t *testing.T) {
	testCases := []struct {
		name string
		root string
		path string
		want string
	}{
		{name: "nested file", root: "/a/b", path: "/a/b/c/d.go", want: "c/d.go"},
		{name: "same dir", root: "/a/b", path: "/a/b/d.go", want: "d.go"},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			got := RelPath(tc.root, tc.path)
			if got != tc.want {
				t.Errorf("RelPath(%q, %q) = %q, want %q", tc.root, tc.path, got, tc.want)
			}
		})
	}
}

func TestIsGeneratedFile(t *testing.T) {
	dir := t.TempDir()
	genPath := filepath.Join(dir, "gen.go")
	realPath := filepath.Join(dir, "real.go")
	os.WriteFile(genPath, []byte("// Code generated by tool\npackage x\n"), 0o644)
	os.WriteFile(realPath, []byte("package x\n"), 0o644)

	if !isGeneratedFile(genPath) {
		t.Error("expected gen.go to be detected as generated")
	}
	if isGeneratedFile(realPath) {
		t.Error("expected real.go to NOT be detected as generated")
	}
}

func writeFile(t *testing.T, dir, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
}

func writeFileDeep(t *testing.T, dir, subdir, name, content string) {
	t.Helper()
	full := filepath.Join(dir, subdir)
	if err := os.MkdirAll(full, 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", full, err)
	}
	if err := os.WriteFile(filepath.Join(full, name), []byte(content), 0o644); err != nil {
		t.Fatalf("write %s/%s: %v", subdir, name, err)
	}
}


func TestTestPairing(t *testing.T) {
	testCases := []struct {
		name  string
		files map[string]string
		want  int
	}{
		{
			name: "source file with matching test file is clean",
			files: map[string]string{
				"a.go":      "package x\nfunc A() {}\n",
				"a_test.go": "package x\nimport \"testing\"\nfunc TestA(t *testing.T) {}\n",
			},
			want: 0,
		},
		{
			name:  "source file with no test file is flagged",
			files: map[string]string{"a.go": "package x\nfunc A() {}\n"},
			want:  1,
		},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			for name, content := range tc.files {
				writeFile(t, dir, name, content)
			}
			got, err := TestPairing(dir)
			if err != nil {
				t.Fatalf("TestPairing: %v", err)
			}
			if len(got) != tc.want {
				t.Errorf("TestPairing() = %d findings, want %d: %v", len(got), tc.want, got)
			}
		})
	}
}

func TestMaxFilesPerDir(t *testing.T) {
	testCases := []struct {
		name      string
		fileCount int
		want      int
	}{
		{name: "8 files is clean", fileCount: 8, want: 0},
		{name: "9 files is flagged", fileCount: 9, want: 1},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			sub := "pkg"
			for i := 0; i < tc.fileCount; i++ {
				name := "f" + string(rune('a'+i)) + ".go"
				writeFileDeep(t, dir, sub, name, "package pkg\n")
			}
			got, err := MaxFilesPerDir(dir)
			if err != nil {
				t.Fatalf("MaxFilesPerDir: %v", err)
			}
			if len(got) != tc.want {
				t.Errorf("MaxFilesPerDir() = %d findings, want %d: %v", len(got), tc.want, got)
			}
		})
	}
}

func TestTestPairing_DeclarationOnlyFileIsExempt(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "types.go", "package x\ntype Rule struct {\n\tID string\n}\nvar Registry = map[string]Rule{}\n")
	got, err := TestPairing(dir)
	if err != nil {
		t.Fatalf("TestPairing: %v", err)
	}
	if len(got) != 0 {
		t.Errorf("declaration-only file should be exempt, got %d findings: %v", len(got), got)
	}
}
